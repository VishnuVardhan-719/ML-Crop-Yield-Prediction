"""Regenerate the static demo report from a real pipeline run on the bundled sample dataset.

The demo must keep working without the backend, so it has to be a fixture. Previously it was
hand-written, and it drifted: it selected Ridge while the shipped metrics made Random Forest the
best model, and it described a file that did not exist. Generating it from an actual run means
the demo and the downloadable sample always tell the same story.

Run from the repository root, after regenerating the sample dataset:

    .venv/Scripts/python.exe backend/scripts/generate_demo_fixture.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

# Make the repository root importable when this is run as a plain script.
ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from backend.app.analysis import build_report, parse_dataset  # noqa: E402

SAMPLE = Path("public/sample-datasets/sample-field-trials.csv")
TARGET = "yield_t_ha"
OUTPUT = Path("src/demo/demoAnalysis.ts")
# A fixture ships inside the JS bundle and is rendered by tests, so it carries a readable sample of
# the holdout rather than all of it. `evidenceTotal` still reports the true count, so the interface
# can say exactly how much it is showing.
EVIDENCE_POINTS = 12
HEADER = """import type { AnalysisReport } from '../types/analysis'

/**
 * Demo fixture: a recorded run of the analysis engine over the bundled sample dataset
 * (`public/sample-datasets/sample-field-trials.csv`).
 *
 * Generated by `backend/scripts/generate_demo_fixture.py` — do not edit by hand. Re-run that
 * script after changing the engine or the sample dataset so the demo cannot drift from reality.
 */
"""


def main() -> None:
    payload = SAMPLE.read_bytes()
    record = parse_dataset(payload, ".csv", SAMPLE.name)
    report = build_report(record, TARGET)

    # Demo-specific framing: the disclosure, the stable id, and the matching file metadata.
    report["analysisId"] = "demo-analysis-001"
    report["source"] = "demo"
    report["dataset"]["fileName"] = SAMPLE.name
    report["dataset"]["fileSize"] = len(payload)
    report["caveats"] = [
        "Demo values come from a recorded run over the bundled sample dataset, not from your upload.",
        "The sample dataset is synthetic and is not a real agricultural survey.",
        *report["caveats"],
    ]
    points = report["prediction"]["actualVsPredicted"][:EVIDENCE_POINTS]
    report["prediction"]["actualVsPredicted"] = points
    report["prediction"]["residuals"] = [point["residual"] for point in points]
    report["prediction"]["evidenceShown"] = len(points)

    body = json.dumps(report, indent=2, ensure_ascii=False)
    OUTPUT.write_text(
        f"{HEADER}export const demoAnalysisReport: AnalysisReport = {body}\n\nexport const runDemoAnalysis = async () => demoAnalysisReport\n", encoding="utf-8"
    )

    selected = next(model for model in report["models"] if model["selected"])
    print(f"wrote {OUTPUT}")
    print(f"  target {TARGET} | {report['dataset']['rows']} rows")
    print(f"  selected {selected['label']} (cv RMSE {selected['rmse']}, R2 {selected['r2']})")
    print(f"  attribution method {report['insightsMethod']}")
    print(f"  caveats {len(report['caveats'])}")


if __name__ == "__main__":
    main()
